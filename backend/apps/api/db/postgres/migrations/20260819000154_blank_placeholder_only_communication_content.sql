-- migrate:up
-- Backfill: blank `ci.communications.content` on rows whose ENTIRE body is
-- placeholder glyphs -- U+FFFC OBJECT REPLACEMENT CHARACTER and/or U+FFFD
-- REPLACEMENT CHARACTER -- imported before the fix that stops the importers
-- writing them.
--
-- ## The bug
--
-- macOS does not store an attachment-only iMessage with an empty body. It
-- stores the body as U+FFFC, the OBJECT REPLACEMENT CHARACTER, at the position
-- the inline attachment sits: a photo sent with no caption has
-- `message.text = U+FFFC`, and a captioned one has
-- `U+FFFC` + " look at this".
--
-- `descriptionFor()` (backend/apps/api/src/domains/import/push/canonical.ts)
-- copied that straight through -- `sanitizeText()` strips C0 controls and
-- repairs lone surrogates, but knew nothing about U+FFFC -- and
-- `toCommunicationInput()` (push/inputs.ts) stored it verbatim as
-- `content`. The result is a row whose only text is one invisible control
-- glyph. The same rows are also where the ATTACHMENT identity should have
-- been: datasources/imessage.ts read `attachment.guid` / `.filename` /
-- `.mime_type` out of chat.db and then discarded all three whenever the bytes
-- did not resolve on disk (which was nearly always -- it built the local path
-- by joining chat.db's tilde-rooted `~/Library/Messages/Attachments/...`
-- value onto `<chat.db dir>/Attachments/`, a path that exists on no machine).
-- So the row recorded neither the text nor what had replaced it.
--
-- U+FFFD is the sibling case: a body that came out of a mis-decoded byte run
-- as nothing but replacement characters. `sanitizeText()` MINTS U+FFFD for
-- lone surrogates, so it deliberately does not strip it; a body that is
-- nothing but U+FFFD carries no recoverable text either way.
--
-- ## Verified against a real appliance database before writing this migration
--
--   SELECT count(*) FROM ci.communications
--    WHERE content ~ ('^' || U&'\FFFC' || '+$');
--   -- 21781 rows whose whole content is U+FFFC (18035 of them a single one)
--
--   SELECT count(*) FROM ci.communications
--    WHERE content ~ ('^' || U&'\FFFD' || '+$');
--   -- 313 rows whose whole content is U+FFFD
--
--   -- Plus 227 rows mixing the two ("U+FFFD U+FFFC"), which the combined
--   -- character class below picks up:
--   SELECT source_system, count(*) FROM ci.communications
--    WHERE content ~ ('^[[:space:]' || U&'\FFFC' || U&'\FFFD' || ']+$')
--      AND content ~ ('[' || U&'\FFFC' || U&'\FFFD' || ']')
--    GROUP BY 1;
--   -- imessage 22320, google_voice 1  (22321 total)
--
--   -- Nothing is recoverable from these rows: the attachment descriptor that
--   -- should have named the missing photo was never written either.
--   SELECT count(*) FILTER (WHERE attachments IS DISTINCT FROM '[]'::jsonb),
--          count(*) FILTER (WHERE preview IS NOT NULL),
--          count(*) FILTER (WHERE subject IS NOT NULL)
--     FROM ci.communications
--    WHERE content ~ ('^[[:space:]' || U&'\FFFC' || U&'\FFFD' || ']+$')
--      AND content ~ ('[' || U&'\FFFC' || U&'\FFFD' || ']');
--   -- 0 | 0 | 0   -- so '' is the only honest value; there is no label to derive
--
--   -- The search index has nothing to go stale: a tsvector built from a
--   -- placeholder glyph has no lexemes at all.
--   SELECT count(*) FROM ci_search.vectors v
--     JOIN ci.communications c ON c.id = v.entity_id
--    WHERE c.content ~ ('^[[:space:]' || U&'\FFFC' || U&'\FFFD' || ']+$')
--      AND v.vector <> ''::tsvector;
--   -- 0
--
--   -- ci.entities carries a MIRROR row per communication whose `name` is the
--   -- displayed label, and every one of the affected rows inherited the glyph:
--   SELECT count(*) FROM ci.entities e
--     JOIN ci.communications c ON c.id = e.entity_id
--    WHERE e.entity_type = 'Communication'
--      AND c.content ~ ('^[[:space:]' || U&'\FFFC' || U&'\FFFD' || ']+$');
--   -- 22321, of which 22321 have a name that is ONLY placeholder glyphs
--   -- (0 already null, 0 with a description) -- so blanking `content` alone
--   -- would leave the glyph on screen everywhere a communication is listed.
--
-- ## Scope: whole-body placeholders ONLY
--
-- 6,660 further rows carry a placeholder glyph NEXT TO real text -- captioned
-- attachments such as "U+FFFC Merry Christmas" or
-- "Also, what is this thing called?U+FFFC". Those are deliberately left alone
-- here: their content is a real message the user wrote, and rewriting it is a
-- different (and riskier) edit than blanking a body that never had any text
-- in it. The forward fix does strip the glyph out of them, so a re-import
-- converges them; this migration does not touch them, which is why the
-- predicate is anchored (`^...$`) rather than a substring match.
--
-- ## The fix
--
-- TWO tables, because the label is derived and stored, not computed on read.
--
-- `ci.entities.name` for a Communication is
-- `subject ?? preview ?? previewFromContent(content)` -- see
-- CommunicationService.labelFor / CommunicationEntity.previewFromContent. With
-- `content` blank all three are empty, so the label a freshly-imported row
-- produces is NULL. Nothing recomputes it after the fact (there is no trigger
-- on ci.communications; the mirror is only upserted when the service writes
-- the row), so the migration has to null it explicitly or the glyph stays
-- visible in every list view even though `content` is clean.
--
-- `content` becomes '' -- which is exactly what a freshly-imported
-- attachment-only message produces after the fix (`isAttachmentPlaceholderOnly`
-- in push/canonical.ts makes `toCommunicationInput` skip the
-- `description ?? title` fallback chain, the same contract
-- `isDiscordAttachmentOnly` already had). `preview` is set to NULL for the same
-- reason migration 20260818213148 does: `toCommunicationInput` only populates
-- `.preview` when it differs from `.content`, so a never-corrupted row of this
-- shape has `preview IS NULL`, and that is what is restored rather than a
-- recomputed value. (All 22,321 rows already have `preview IS NULL`; the
-- assignment is there so the invariant holds on any database where they do
-- not.)
--
-- ## Why this is not theatre
--
-- The generator is fixed in the same change, so re-importing the same chat.db
-- does not re-create these rows:
--   * push/canonical.ts `sanitizeText()` now strips U+FFFC, so a captioned
--     attachment yields the caption alone and an uncaptioned one yields null;
--   * push/canonical.ts `isAttachmentPlaceholderOnly()` + push/inputs.ts keep
--     `content` EMPTY for such a record instead of falling through to
--     `titleFor`, which would otherwise synthesize a "Message - <sender>"
--     label the user never wrote;
--   * datasources/imessage.ts now stamps the attachment guid/filename/MIME
--     onto the message whether or not the bytes resolve, and resolves the
--     tilde-rooted chat.db path against the export root, so the descriptor
--     that belongs in place of the glyph is actually recorded.
--
-- Idempotent: both WHERE clauses are the same predicate used to find the
-- corruption. After the updates `content` is '' and `name` is NULL, neither of
-- which matches (the character class requires at least one glyph), so a second
-- run updates zero rows in either table.
-- The mirror label first, while the corruption is still identifiable by the
-- same predicate on both sides. Scoped to Communication mirrors and anchored,
-- so a Content/Event entity that merely CONTAINS a glyph is not touched.
UPDATE ci.entities
   SET name = NULL
 WHERE entity_type = 'Communication'
   AND name ~ ('^[[:space:]' || U&'\FFFC' || U&'\FFFD' || ']+$')
   AND name ~ ('[' || U&'\FFFC' || U&'\FFFD' || ']');

UPDATE ci.communications
   SET content = '',
       preview = NULL
 WHERE content ~ ('^[[:space:]' || U&'\FFFC' || U&'\FFFD' || ']+$')
   AND content ~ ('[' || U&'\FFFC' || U&'\FFFD' || ']');

