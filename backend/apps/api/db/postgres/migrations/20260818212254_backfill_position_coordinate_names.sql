-- migrate:up
-- Backfill: null out ci.position.name where it holds a coordinate pair
-- instead of a place name — the rows ffe607646 ("a coordinate pair is not a
-- place name") stopped a NEW import from writing.
--
-- ffe607646 fixed `toPositionInput` (backend/apps/api/src/domains/import/push/
-- inputs.ts) so google_fit's trackpoint fallback ("33.51469, -117.72169", used
-- as the item's DISPLAY title when a fix has no waypoint name) never lands in
-- `ci.position.name` again. It did not touch rows already written under the
-- old behaviour — this migration is that one-time recovery.
--
-- ## Why a coordinate-shaped `name` matters
--
-- `PositionReverseStage`'s candidate predicate
-- (backend/apps/api/src/domains/pipeline/stages/enrich/PositionReverseStage.ts,
-- `POSITION_REVERSE_SOURCE.predicate`) is `location IS NOT NULL AND id IS NOT
-- NULL` — it has never inspected `name`, so a coordinate-named row was always
-- as eligible for reverse-geocoding as any other. What the fake name actually
-- breaks is display: it stood in for a real place name in every view that
-- reads `ci.position.name` (Places, position detail), and — because
-- `writeAddresses` only fills `name` from a provider `point_of_interest` /
-- `establishment` / `premise` component and most GPS fixes have no venue
-- (`ADDRESS_COMPONENT_RULE` leaves `name` NULL in that case, deliberately,
-- per that file's own comment) — a completed reverse-geocode pass would still
-- leave the majority of these 62,832 rows displaying their own geometry as
-- their name, underneath a freshly-resolved `address`. This migration is
-- deliberately narrow: it only clears `name`, so no other column is touched
-- and this stays safe to run whether or not the reverse-geocode sweep has
-- ever run against these rows.
--
-- ## The pattern, reused verbatim
--
-- Exactly `isCoordinateText` from inputs.ts — two signed decimals separated
-- by a comma, nothing else. "Cafe 40.7, 74.0" is untouched: a place whose
-- name happens to contain numbers is still a name. It also does not match the
-- separate, smaller set of rows holding a raw media filename instead of
-- coordinates or a place name (e.g. "07683A42-...-....mov") — a different,
-- out-of-scope bug; confirmed zero overlap against the live data before
-- writing this migration.
--
-- ## Verified against a real appliance database before writing this migration
--
--   SELECT count(*) FROM ci.position
--    WHERE name ~ '^\s*[-+]?\d{1,3}(?:\.\d+)?\s*,\s*[-+]?\d{1,3}(?:\.\d+)?\s*$';
--   -- 62832, of 63179 total ci.position rows (all of which had a non-NULL
--   -- name going in — 0 rows currently read as reverse-geocode candidates
--   -- under a `name IS NULL` filter, which is a different, name-*sensitive*
--   -- filter than the one this stage actually uses; see above).
--
-- Idempotent: NULL fails every `~` comparison (NULL, not false), so a second
-- run's WHERE matches nothing and updates zero rows.
UPDATE ci.position
   SET name = NULL
 WHERE name ~ '^\s*[-+]?\d{1,3}(?:\.\d+)?\s*,\s*[-+]?\d{1,3}(?:\.\d+)?\s*$';

