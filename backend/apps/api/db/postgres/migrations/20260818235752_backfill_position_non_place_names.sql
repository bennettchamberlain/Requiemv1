-- Backfill: null out ci.position.name where it holds a MEDIA FILENAME or a
-- LABELLED COORDINATE PAIR instead of a place name.
--
-- The direct sequel to 20260818212254_backfill_position_coordinate_names,
-- which cleared the BARE coordinate pair ("33.51469, -117.72169") and said in
-- its own header that the filename rows were "a different, out-of-scope bug".
-- This is that bug, plus the variant of its own bug that its predicate could
-- not see. The two classes ship together because they are one defect —
-- a string that is not the name of a place, written into the column that names
-- the place — and one code fix (`isNotAPlaceName` in
-- backend/apps/api/src/domains/import/push/inputs.ts) now blocks both.
--
-- ## Class 1: media filenames (2,085 rows on a real appliance)
--
-- Every GPS-bearing photo donates a position row, and `titleFor`
-- (push/canonical.ts) gives a `capture.*` item its FILENAME as a display title
-- — correctly, because a filename is the only label a photo has.
-- `toPositionInput` then read that title as the position's NAME, so the Places
-- view rendered "IMG_0139.JPG", "20140710_170940.jpg" and
-- "A20CEAAC-8F30-403E-A17B-E60DBC744DBB_3.mov" as though they were places.
-- The same title/name split google_fit's coordinates fell through.
--
-- ## Class 2: labelled coordinate pairs
--
-- `isCoordinateText` was anchored `^\s*[-+]?\d`, so it only ever saw a pair
-- that STARTS with its number. Three registered datasources emitted the pair
-- behind a label and sailed straight through:
--
--   datasources/google_location.ts  Title: `Location ${lat}, ${lon}`
--   datasources/kmlgx.ts            Name:  `Location ${lat},${lon}`
--   datasources/nmea.ts             Name:  `Location ${lat}, ${lon}`
--
-- All three now emit no name at all (that is the real fix — the string is no
-- longer minted, so this backfill cannot be undone by a re-import), and the
-- predicate was widened to tolerate one generic geo-noun label as the backstop
-- for producers we do not own.
--
-- ## Why NULL is the right value
--
-- A null name is what makes a row a reverse-geocode candidate in every
-- name-sensitive view and query ("coordinates present, name missing"). A fake
-- name is strictly worse than no name: it displays as though the place were
-- already known, so nothing ever offers it a real one. Narrow on purpose —
-- only `name` is touched; geometry, address, source and provider are untouched,
-- so this is safe whether or not the reverse-geocode sweep has run.
--
-- ## Disjoint from 20260818212254
--
-- The coordinate arm here REQUIRES the label prefix, so it cannot re-match the
-- bare pairs that migration already cleared (verified 0 remaining, below), and
-- the two arms do not overlap each other (verified 0, below).
--
-- ## Verified against a real appliance database before writing this migration
--
--   SELECT count(*) FROM ci.position;                                  -- 65115
--   SELECT count(*) FROM ci.position WHERE name IS NULL;               -- 62300
--
--   -- Class 1, media extension:
--   SELECT count(*) FROM ci.position
--    WHERE name ~* '\.(jpe?g|png|heic|heif|gif|mov|mp4|m4v|avi|webp|dng|tiff?)$';
--   -- 2085 (2063 distinct). Every one is a camera-roll filename; the only one
--   -- containing whitespace is '2015-01-27 16.56.57.jpg', still a filename.
--
--   -- Class 1, bare UUID stem (an export that dropped the extension):
--   SELECT count(*) FROM ci.position
--    WHERE name ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}([-_][0-9]+)?$';
--   -- 0 in this corpus — carried anyway because the code predicate carries it
--   -- and an Apple-sourced export is one `basename` away from producing it.
--
--   -- Class 2, labelled coordinate pair:
--   SELECT count(*) FROM ci.position
--    WHERE name ~* '^\s*(location|position|coordinates?|coords?|point|waypoint|fix|gps)\s*[-:]?\s*[-+]?\d{1,3}(\.\d+)?\s*,\s*[-+]?\d{1,3}(\.\d+)?\s*$';
--   -- 0 in this corpus (none of google_location/kmlgx/nmea ran against it);
--   -- carried because those parsers are registered and any appliance that ran
--   -- one has the rows.
--
--   -- Already cleared by 20260818212254, and not re-matched here:
--   SELECT count(*) FROM ci.position
--    WHERE name ~ '^\s*[-+]?\d{1,3}(\.\d+)?\s*,\s*[-+]?\d{1,3}(\.\d+)?\s*$';  -- 0
--
--   -- The two arms do not overlap:                                    -- 0
--
--   -- Real place names in the same column, none of which any predicate here
--   -- matches: 'Las Vegas Convention Center', 'A.G. Bartlett Building',
--   -- 'Pico / Figueroa', '75 Amherst St, Cambridge, MA 02139, USA', '1011-7'.
--
-- ## The patterns, mirrored from inputs.ts
--
-- `[-:]` and not `[:-]` on purpose: the same two characters, ordered so the
-- bracket expression cannot be misread as the start of a POSIX character-class
-- name (`[:alpha:]`). The label vocabulary is generic geolocation nouns ONLY —
-- no venue words — so 'Cafe 40.7, 74.0' and 'Pier 39, 94133' keep their names,
-- the same guarantee `isCoordinateText` has always given.
--
-- Idempotent: NULL fails every `~*`/`~` comparison (NULL, not false), so once a
-- row is cleared it can never match again and a second run updates zero rows.
--
-- Every arm compares btrim(name), matching `isMediaFilename`, which trims before
-- testing. Without it a name carrying stray whitespace is rejected by the code
-- and missed here, so the guard and the backfill would disagree about the same
-- string — the exact drift these paired predicates exist to prevent.
--
-- The URI arm mirrors `isUriLocation`, the third reject in `isNotAPlaceName`.
-- No earlier migration has ever cleared a URI-shaped name from ci.position (the
-- calendar one, 20260818215813, only touches ci.events), so this is its first
-- pass over this table.
UPDATE ci.position
   SET name = NULL
 WHERE btrim(name) ~* '\.(jpe?g|png|heic|heif|gif|mov|mp4|m4v|avi|webp|dng|tiff?)$'
    OR btrim(name) ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}([-_][0-9]+)?$'
    OR btrim(name) ~* '^[a-z][a-z0-9+.-]*://\S+$'
    OR btrim(name) ~* '^\s*(location|position|coordinates?|coords?|point|waypoint|fix|gps)\s*[-:]?\s*[-+]?\d{1,3}(\.\d+)?\s*,\s*[-+]?\d{1,3}(\.\d+)?\s*$';

